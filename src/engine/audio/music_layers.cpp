std::optional<std::array<std::uint8_t, 16>> song_layers(std::string_view name) {
    for (std::size_t i = 0; i < 40; ++i) {
        if (kSongs[i] == name) {
            std::array<std::uint8_t, 16> row{};
            for (std::size_t ch = 0; ch < 16; ++ch) {
                row[ch] = kLayers[i + 1][ch];
            }
            return row;
        }
    }
    return std::nullopt;
}

