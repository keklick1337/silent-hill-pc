#include "formats/convert/anim/anim_clips.h"

#include "formats/common/json.h"

#include <algorithm>
#include <cctype>

namespace sh::convert::anim {

extern const char* const kBuiltinClipsJson;  // anim_clips_data.cpp, generated by CMake from anim_clips.json

namespace {

std::string upper(std::string_view s) {
    std::string out(s);
    std::transform(out.begin(), out.end(), out.begin(), [](unsigned char c) { return static_cast<char>(std::toupper(c)); });
    return out;
}

}  // namespace

Result<ClipCatalog> parse_clip_catalog(std::string_view json_text) {
    using Out = Result<ClipCatalog>;
    auto doc = json::parse(json_text);
    if (!doc) {
        return Out::fail("anim clips: " + doc.error());
    }
    const json::Value* anm = doc.value().find("anm");
    if (!anm || !anm->is_object()) {
        return Out::fail("anim clips: no \"anm\" object");
    }
    ClipCatalog catalog;
    for (const auto& [path, entry] : anm->members()) {
        const json::Value* clips = entry.find("clips");
        if (!clips || !clips->is_array()) {
            return Out::fail("anim clips: " + path + " has no clips array");
        }
        std::vector<Clip>& out = catalog[upper(path)];
        for (const json::Value& c : clips->array()) {
            const json::Value* name = c.find("name");
            const json::Value* start = c.find("start");
            const json::Value* end = c.find("end");
            if (!name || !name->is_string() || !start || !start->is_integer() || !end || !end->is_integer()) {
                return Out::fail("anim clips: " + path + ": a clip needs name, start and end");
            }
            Clip clip;
            clip.name = name->string();
            clip.start = static_cast<int>(start->integer());
            clip.end = static_cast<int>(end->integer());
            if (const json::Value* v = c.find("fps"); v && v->is_number()) {
                clip.fps = v->number();
            }
            if (const json::Value* v = c.find("loop"); v && v->is_bool()) {
                clip.loop = v->boolean();
            }
            if (const json::Value* v = c.find("variable_speed"); v && v->is_bool()) {
                clip.variable_speed = v->boolean();
            }
            if (const json::Value* v = c.find("reverse"); v && v->is_bool()) {
                clip.reverse = v->boolean();
            }
            if (clip.start < 0 || clip.end < clip.start) {
                return Out::fail("anim clips: " + path + ": clip " + clip.name + " has a bad keyframe range");
            }
            out.push_back(std::move(clip));
        }
    }
    return Out::ok(std::move(catalog));
}

const ClipCatalog& builtin_clips() {
    static const ClipCatalog catalog = [] {
        auto parsed = parse_clip_catalog(kBuiltinClipsJson);
        return parsed ? std::move(parsed.value()) : ClipCatalog{};
    }();
    return catalog;
}

std::vector<Clip> clips_for(const ClipCatalog& catalog, std::string_view anm_path) {
    const auto it = catalog.find(upper(anm_path));
    return it == catalog.end() ? std::vector<Clip>{} : it->second;
}

}  // namespace sh::convert::anim
