#!/usr/bin/env python3
"""Writes map_layout.inc: where the point and event tables of every map are in its file on the disc.

A one-time generator: map_layout.inc is committed and final for the supported disc, and nothing runs this script
in a build or a check. It reads a checkout of the decompilation (shdecompilations/silent-hill-decomp, see
docs/DEVELOPMENT.md section 7), which is not part of this repository.

Usage: python3 -I gen_map_layout.py <root of the decompilation checkout> > map_layout.inc

MAP_POINTS and MAP_EVENTS: address from configs/USA/maps/sym.<map>.txt; entry count of MAP_POINTS from
src/maps/<map>/map_points.h (it must equal the gap to the next symbol / 12), of MAP_EVENTS from the array size in
src/maps/<map>/map_events.c (the symbol after it is further away: other data follows without a symbol).
"""
import os
import re
import sys

if len(sys.argv) != 2 or sys.argv[1] in ("-h", "--help"):
    sys.exit(__doc__)
root = sys.argv[1]
maps_dir = os.path.join(root, "src", "maps")
sym_dir = os.path.join(root, "configs", "USA", "maps")
if not os.path.isdir(maps_dir) or not os.path.isdir(sym_dir):
    sys.exit(f"error: {root} is not a checkout of the decompilation (no src/maps and configs/USA/maps in it)")
maps = sorted(d for d in os.listdir(maps_dir) if re.fullmatch(r"map\d_s\d\d", d))

print("// Generated by gen_map_layout.py; do not edit.")
print("// map, MAP_POINTS address, count, MAP_EVENTS address, count")
for m in maps:
    syms = {}
    with open(os.path.join(sym_dir, f"sym.{m}.txt")) as f:
        for line in f:
            mm = re.match(r"\s*(\w+)\s*=\s*0x([0-9A-Fa-f]+);", line)
            if mm:
                syms[mm.group(1)] = int(mm.group(2), 16)
    addrs = sorted(set(syms.values()))
    points = syms["MAP_POINTS"]
    events = syms["MAP_EVENTS"]
    with open(os.path.join(maps_dir, m, "map_points.h")) as f:
        point_count = len(re.findall(r"^    \{\s*$", f.read(), re.M))
    gap = min(a for a in addrs if a > points) - points
    if gap != point_count * 12:
        sys.exit(f"{m}: MAP_POINTS has {point_count} entries but {gap} bytes to the next symbol")
    with open(os.path.join(maps_dir, m, "map_events.c")) as f:
        event_count = int(re.search(r"MAP_EVENTS\[(\d+)\]", f.read()).group(1))
    print(f'{{"{m}", 0x{points:08X}, {point_count}, 0x{events:08X}, {event_count}}},')
