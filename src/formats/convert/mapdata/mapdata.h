#pragma once

// Data of the map overlays (VIN/MAPn_Snn.BIN) as JSON in gamedata/maps/<map>/.
//
// An overlay is code and data in one file. This module reads the data parts at their addresses in the NTSC USA 1.1
// overlays, writes them as JSON a modder can edit, reads the JSON back, and writes the same bytes again:
// encode(read(write(decode(overlay)))) gives the overlay's bytes for every part. The game reads the JSON through
// sh_maps (src/engine/maps/).

#include "formats/common/status.h"
#include "formats/convert/mapdata/map_records.h"

#include <array>
#include <cstdint>
#include <span>
#include <string>
#include <string_view>
#include <vector>

namespace sh::convert::mapdata {

// Every overlay is loaded at the same address.
inline constexpr std::uint32_t kOverlayBase = 0x800C9578;
// The map header (the original's s_MapOverlayHdr) is the first data after a 4-byte rodata word; 0x104C bytes in
// the PS1 layout.
inline constexpr std::uint32_t kHeaderOffset = 0x4;
inline constexpr std::uint32_t kHeaderSize = 0x104C;

// Where a map's arrays lie (map_layout.inc, generated by gen_map_layout.py).
struct MapLayout {
    std::string_view map;  // "map1_s02"
    std::uint32_t points_va;
    std::uint16_t point_count;
    std::uint32_t events_va;
    std::uint16_t event_count;
};

std::span<const MapLayout> map_layouts();
const MapLayout* find_layout(std::string_view map);

// "map1_s02" -> "VIN/MAP1_S02.BIN"
std::string overlay_path(std::string_view map);

// One kind of data = one JSON file of gamedata/maps/<map>/.
enum class Kind : std::uint8_t { Header, Spawns, Points, Events, Cameras, Collision };
inline constexpr std::array<Kind, 6> kAllKinds = {Kind::Header, Kind::Spawns,  Kind::Points,
                                                  Kind::Events, Kind::Cameras, Kind::Collision};

// "spawns" (file name without ".json").
std::string_view kind_name(Kind kind);

// Story-driven spawn overrides: condition + flag writes applied by
// the generic selector at overlay load through the game's Chara_SpawnFlagsSet. Names, not numbers:
// the game resolves character and flag names through its own registries when applying. Only the
// unified map.json carries the section; the importer never writes it (it is hand/mod data).
struct SpawnFlagSet {
    std::string chara;                    // e_Chara name ("GreyChild")
    int slot = 0;                         // index into the map's spawn table
    std::vector<std::string> flags;       // e_SpawnFlags names ("none", "spawn_0".."spawn_4")
};
struct SpawnCondition {
    /* Difficulty is stored as e_GameDifficulty {Easy=-1, Normal=0, Hard=1};
     * the DATA names them "easy"/"normal"/"hard" — raw numbers are never read. Unset fields do
     * not constrain; several present must all hold (exact, inclusive min, inclusive max). */
    static constexpr int kDifficultyUnset = 1000;
    int difficulty = kDifficultyUnset;      // exact match
    int difficulty_min = kDifficultyUnset;  // inclusive lower bound
    int difficulty_max = kDifficultyUnset;  // inclusive upper bound
    std::vector<std::string> flags_set;   // every listed flag must be set
    std::vector<std::string> flags_clear; // every listed flag must be clear
    std::vector<SpawnCondition> all;      // nested groups: every sub-condition matches
    std::vector<SpawnCondition> any;      // at least one sub-condition matches
};
struct SpawnOverride {
    SpawnCondition when;
    std::vector<SpawnFlagSet> set;
};

// Spawn variants: whole alternative spawn tables of one map,
// one of which the generic selector copies over the map's table, plus the killed-enemy memory that
// travels with it. A variant's rows come either from the imported map data (the overlay's own
// alternative tables, MapData::spawn_variant_rows, found by the variant's name, so no disc data lives
// in the repository) or inline (a mod's own rows).
inline constexpr int kSpawnTableRows = SH_MAP_SPAWN_GROUPS * SH_MAP_SPAWN_SLOTS;  // row = group * 16 + slot
// One alternative table of the overlay, named by the importer (map.json "spawn_variant_rows").
struct SpawnVariantRows {
    std::string name;
    std::array<ShMapSpawn, kSpawnTableRows> rows{};
};
struct SpawnVariant {
    std::string name;                 // readable id the choices refer to ("ChurchStreets")
    bool rows_inline = false;         // the "rows" array was given; otherwise the map's table of this name
    bool rows_resolved = false;       // rows holds the values (inline, or from the map's tables)
    std::array<ShMapSpawn, kSpawnTableRows> rows{};
    int enemy_state_load = -1;        // save's ovlEnemyStates word copied INTO the active word on apply
    int enemy_state_save = -1;        // word the active word is copied back to while the map runs
};
struct SpawnVariantChoice {
    SpawnCondition when;
    std::string variant;                       // SpawnVariant::name
    std::vector<std::string> set_flags;        // event flags set when this choice is taken
};
struct SpawnVariants {
    int enemy_state_active = -1;               // the map's own ovlEnemyStates word (the one the game uses)
    std::vector<SpawnVariant> variants;
    std::vector<SpawnVariantChoice> choices;   // first match wins; no match: no variant
    bool present() const { return !variants.empty(); }
};

// Fills the rows of every variant without inline rows from the map's table of the same name.
// Fails, naming the variant, when the map has no such table.
Result<void> resolve_spawn_variant_rows(const std::vector<SpawnVariantRows>& tables, SpawnVariants& variants);

struct MapData {
    std::string map;
    ShMapHeaderInfo header{};
    ShMapSpawns spawns{};
    std::vector<SpawnOverride> spawn_overrides;  // unified map.json only; empty = no section
    SpawnVariants spawn_variants;                // hand file spawn_overrides.json only; empty = none
    std::vector<SpawnVariantRows> spawn_variant_rows;  // the overlay's alternative tables (decode_overlay,
                                                       // map.json "spawn_variant_rows"); most maps: none
    std::vector<ShMapPoint> points;
    std::vector<ShMapEvent> events;
    std::array<ShMapCamera, SH_MAP_CAMERA_PATHS> cameras{};
    std::array<ShMapCollision, SH_MAP_COLLISION_COUNT> collision{};
};

// A part of the overlay file that one kind occupies.
struct Region {
    Kind kind;
    std::uint32_t offset;  // in the file
    std::uint32_t size;
};

// The parts of the overlay that hold the data of `layout`; the header kind is several small parts.
std::vector<Region> regions(const MapLayout& layout);

// Reads all kinds from the overlay. Fails when the file is too short or the header's pointers to the map points
// and events disagree with the layout (another game version or a broken file). Also reads the overlay's
// alternative spawn tables the importer knows of (spawn_variant_rows; mapdata_binary.cpp).
Result<MapData> decode_overlay(std::span<const std::uint8_t> overlay, const MapLayout& layout);

// Writes `kind` of `data` into `overlay` (a copy of the file) at its regions. The counts of points and events must
// equal the layout's: the game's arrays have that size.
Result<void> encode_kind(const MapData& data, Kind kind, const MapLayout& layout, std::span<std::uint8_t> overlay);

// Names of the numbers the map data refers to: event flags
// ("required_flag": "M1S03_ShotgunShells0") and items ("required_item": "LibraryReserveKey").
// The game installs them before it imports or reads a map (src/engine/ids/game_numbers.cpp); without
// them (a tool) the files carry the numbers. Readers take a name or a number either way.
struct IdNaming {
    const char* (*flag_name)(int bit) = nullptr;        // full id, nullptr: the bit has no name
    int (*flag_number)(const char* name) = nullptr;     // -1: unknown
    const char* (*item_name)(int number) = nullptr;
    int (*item_number)(const char* name) = nullptr;
    // A map's message by number (the common block, then the map's own lines) and back: the keys of
    // gamedata/text/en. nullptr / -1: the number has no key, the key is not one of the map's.
    const char* (*message_key)(std::string_view map, int number) = nullptr;
    int (*message_number)(std::string_view map, std::string_view key) = nullptr;
};
void set_id_naming(const IdNaming& naming);

// Spawn characters are named by the table of e_Chara (gamedata carries no numeric ids):
// "GreyChild" of chara_name_of(8), chara_number_of("GreyChild") == 8,
// -1 for unknown names, nullptr for ids without a name (those stay numbers in the files).
const char* chara_name_of(int id);
int chara_number_of(const char* name);

// JSON text of one kind (pretty, ends with a newline).
std::string write_json(const MapData& data, Kind kind);

// Parses the JSON text of `kind` into `data` (only that kind's fields). Errors name the line, column and field.
// Values for a modder: positions in metres and angles in degrees; the *_q12/_q4/_q8 integer beside each is the
// same value in the game's units. When both are present and disagree, the human unit wins and a warning is added.
Result<void> read_json(std::string_view text, Kind kind, const MapLayout& layout, MapData& data,
                       std::vector<std::string>& warnings);

// Bytes of `kind` in the overlay against those `data` gives: one line per differing region, empty when equal.
std::vector<std::string> compare_kind(const MapData& data, Kind kind, const MapLayout& layout,
                                      std::span<const std::uint8_t> overlay);

// The unified scene view map.json: the six
// kinds joined into one file with typed entities (door / message / callback ...). The handler names
// come from the sibling handlers.json (checked by tools/scripts/check_map_handlers.py).

// One entry of handlers.json: index into the map's g_MapEventFuncs table.
struct HandlerInfo {
    int index = 0;
    std::string symbol;  // the g_MapEventFuncs entry; events.lua defines a function of this name
    std::string name;    // readable name for people and tools; empty: none yet
    std::string shape;   // "item", "cutscene" or "script"
};

// Parses handlers.json text (null-symbol slots are skipped). Errors name the position.
Result<std::vector<HandlerInfo>> read_handlers_json(std::string_view text);

// Writes the unified map.json (pretty, ends with a newline). Handler lookup by event param.
// Lossless: every bit of the six kinds has a member, so read_unified_json gives back the
// same records as the separate files.
std::string write_unified_json(const MapData& data, std::span<const HandlerInfo> handlers);

// Parses the unified map.json into all six kinds' fields of `data` at once. The points
// and entities counts must equal the layout's, like the separate files. A mod can ship
// a map.json alone; the six kind files become unnecessary for it.
/* The hand/mod file maps/<map>/spawn_overrides.json: {format, version, spawn_overrides,
 * spawn_variants?}. Parses the entries (the same shape as the map.json section) and APPENDS them to
 * data.spawn_overrides; an optional "spawn_variants" object REPLACES data.spawn_variants (rows named
 * by the map's tables stay unresolved until resolve_spawn_variant_rows). */
Result<void> read_spawn_overrides_file(std::string_view text, MapData& data,
                                       std::vector<std::string>& warnings);
Result<void> read_unified_json(std::string_view text, const MapLayout& layout, MapData& data,
                               std::vector<std::string>& warnings);

}  // namespace sh::convert::mapdata
