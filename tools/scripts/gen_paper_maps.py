#!/usr/bin/env python3
"""Generate gamedata/paper_maps.json: the game's paper maps by name.

A paper map is one page of the navigation map screen, kept in the save by name and named in
scripts (sh.event_paper_map_take("FogSchool1F", ...)). gamedata/paper_maps.json carries the
names, never the numbers: the pages are listed in the game's page order, so the engine (sh::ids,
game_numbers.h) knows the number of a name by its place.

The file is committed and final. Without --upstream the script writes it again from itself in
its canonical form, and --check (the gate) fails when the committed file is not in that form.

--upstream <map.h> takes the names from include/bodyprog/map/map.h of a checkout of the
decompilation (not part of this repository), for the day it names a page that has none yet:
a name is its e_PaperMapIdx name without the prefix (PaperMapIdx_FogSchool1F -> FogSchool1F),
a page it has not named (PaperMapIdx_24) is PaperMap24. Descriptions already given are kept.

Usage: python3 -I tools/scripts/gen_paper_maps.py [--check] [--upstream <map.h>]
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "gamedata" / "paper_maps.json"

DESCRIPTION = (
    "The paper map pages of the game, by name. Each key of \"paper_maps\" is a page id. Scripts and data use these "
    "names: sh.event_paper_map_take, sh.paper_map_state / cmd, the save's paper_map_idx, "
    "config/paper_map_reveals.json and menu/map_screen.json. The order is the page number the game uses, so "
    "never reorder or remove pages. A mod adds pages with a paper_maps.json of the same shape in its folder "
    "(ids are namespaced by the mod folder). Generated by tools/scripts/gen_paper_maps.py, which keeps given"
    " names."
)


def parse_upstream(text: str) -> dict[str, int]:
    """The e_PaperMapIdx block of the decompilation's header: name -> number."""
    block = re.search(r"typedef enum _PaperMapIdx(.*?)\}\s*e_PaperMapIdx;", text, re.S)
    if block is None:
        sys.exit("error: no e_PaperMapIdx enum in the header")
    entries: dict[str, int] = {}
    for name, number in re.findall(r"PaperMapIdx_(\w+)\s*=\s*(\d+)", block.group(1)):
        plain = name[0].isdigit() and f"PaperMap{name}" or name  # PaperMapIdx_24 -> PaperMap24
        if plain in entries and entries[plain] != int(number):
            sys.exit(f"error: {plain} appears twice in e_PaperMapIdx")
        entries[plain] = int(number)
    if not entries:
        sys.exit("error: e_PaperMapIdx enum is empty")
    return entries


def load_descriptions() -> dict[str, dict]:
    if not OUT.exists():
        return {}
    data = json.loads(OUT.read_text(encoding="utf-8"))
    return {name: fields for name, fields in data.get("paper_maps", {}).items()
            if isinstance(fields, dict) and fields}


def paper_maps_json(names: list[str], keep: dict[str, dict]) -> str:
    maps = {name: keep.get(name, {}) for name in names}
    out = {
        "format": "sh-paper-maps",
        "version": 1,
        "description": DESCRIPTION,
        "paper_maps": maps,
    }
    return json.dumps(out, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare the files, write nothing")
    parser.add_argument("--upstream", type=Path,
                        help="include/bodyprog/map/map.h of a checkout of the decompilation: take the names from it")
    args = parser.parse_args()

    if args.upstream is not None:
        if not args.upstream.is_file():
            sys.exit(f"error: {args.upstream} is not a file (--upstream wants include/bodyprog/map/map.h of a "
                     f"checkout of the decompilation)")
        entries = parse_upstream(args.upstream.read_text(encoding="utf-8"))
    elif OUT.exists():
        data = json.loads(OUT.read_text(encoding="utf-8"))
        entries = {name: i for i, name in enumerate(data.get("paper_maps", {}))}
    else:
        sys.exit(f"error: {OUT} is missing; write it with --upstream <map.h>")

    ordered = sorted(entries.items(), key=lambda item: item[1])
    if [number for _, number in ordered] != list(range(len(ordered))):
        sys.exit("error: e_PaperMapIdx has a gap: the pages would not be numbered by place")
    keep = load_descriptions()
    unknown = sorted(set(keep) - set(entries))
    for name in unknown:
        print(f"warning: {name} of paper_maps.json is not in e_PaperMapIdx; kept as-is")

    json_text = paper_maps_json([name for name, _ in ordered], keep)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != json_text:
            print(f"error: {OUT.relative_to(ROOT)} is not up to date"
                  f" (run: python3 -I tools/scripts/gen_paper_maps.py)")
            return 1
        return 0
    OUT.write_text(json_text, encoding="utf-8")
    print(f"paper maps: {len(ordered)} names -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
