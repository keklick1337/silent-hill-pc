#!/usr/bin/env python3
"""Writes src/i18n/core/unicode_data.inc: the Unicode properties the text layout needs.

The data comes from Python's own unicodedata module (its Unicode version is written into the
file), so nothing is downloaded: bidirectional classes, nonspacing marks, the Arabic
presentation forms with the joining behaviour they imply, lam-alef ligatures and the canonical
compositions of a base letter with one mark. The mirrored pairs are listed here by hand
(unicodedata knows that a character mirrors, not what it mirrors to).

  gen_unicode_tables.py           rewrite the file
  gen_unicode_tables.py --check   exit 1 when the committed file differs
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "i18n" / "core" / "unicode_data.inc"
LAST = 0x10FFFF

# The classes the layout tells apart; explicit embedding and isolate controls are dropped from
# the text before the rules run, so they are boundary neutrals here.
BIDI = {"L": "L", "R": "R", "AL": "AL", "EN": "EN", "ES": "ES", "ET": "ET", "AN": "AN", "CS": "CS",
        "NSM": "NSM", "BN": "BN", "B": "B", "S": "S", "WS": "WS", "ON": "ON",
        "LRE": "BN", "RLE": "BN", "LRO": "BN", "RLO": "BN", "PDF": "BN",
        "LRI": "BN", "RLI": "BN", "FSI": "BN", "PDI": "BN", "": "L"}

MIRRORED = "()[]{}<>«»‹›⁅⁆⁽⁾₍₎≤≥≪≫⌈⌉⌊⌋〈〉❨❩❪❫❬❭❮❯❰❱❲❳❴❵⟦⟧⟨⟩⟪⟫⦃⦄⦅⦆〈〉《》「」『』【】〔〕〖〗〘〙〚〛（）［］｛｝＜＞｟｠｢｣"
# The pairs rule N0 resolves as brackets (a subset of the mirrored pairs: no angle quotes, no relations).
BRACKETS = "()[]{}⁅⁆⁽⁾₍₎⌈⌉⌊⌋〈〉❨❩❪❫❬❭❮❯❰❱❲❳❴❵⟦⟧⟨⟩⟪⟫⦃⦄⦅⦆〈〉《》「」『』【】〔〕〖〗〘〙〚〛（）［］｛｝｟｠｢｣"


def ranges(prop) -> list[tuple[int, int, str]]:
    """Maximal runs of code points with the same non-default value of prop(cp)."""
    out: list[tuple[int, int, str]] = []
    start, cur = 0, prop(0)
    for cp in range(1, LAST + 2):
        v = prop(cp) if cp <= LAST else None
        if v != cur:
            if cur:
                out.append((start, cp - 1, cur))
            start, cur = cp, v
    return out


def bidi_class(cp: int) -> str:
    c = BIDI[unicodedata.bidirectional(chr(cp))]
    if c == "L" and unicodedata.category(chr(cp)) == "Cn":
        # Unassigned code points of the right-to-left blocks default to R / AL.
        if 0x0590 <= cp <= 0x05FF or 0x07C0 <= cp <= 0x085F or 0xFB1D <= cp <= 0xFB4F or 0x10800 <= cp <= 0x10FFF \
                or 0x1E800 <= cp <= 0x1EFFF:
            return "R"
        if 0x0600 <= cp <= 0x07BF or 0x0860 <= cp <= 0x08FF or 0xFB50 <= cp <= 0xFDFF or 0xFE70 <= cp <= 0xFEFF \
                or 0x1EC70 <= cp <= 0x1ECBF or 0x1EE00 <= cp <= 0x1EEFF:
            return "AL"
    return "" if c == "L" else c


def is_mark(cp: int) -> str:
    return "M" if unicodedata.category(chr(cp)) in ("Mn", "Me") else ""


def arabic() -> tuple[list[tuple[int, int, int, int, int]], list[tuple[int, int, int]]]:
    """(base, isolated, final, initial, medial) per letter and (alef, isolated, final) per lam-alef."""
    forms: dict[int, dict[str, int]] = {}
    ligatures: dict[int, dict[str, int]] = {}
    for cp in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFF00)):
        parts = unicodedata.decomposition(chr(cp)).split()
        if not parts or parts[0] not in ("<isolated>", "<final>", "<initial>", "<medial>"):
            continue
        kind = parts[0][1:-1]
        seq = [int(p, 16) for p in parts[1:]]
        if len(seq) == 1:
            forms.setdefault(seq[0], {}).setdefault(kind, cp)
        elif len(seq) == 2 and seq[0] == 0x0644 and kind in ("isolated", "final") and 0xFEF5 <= cp <= 0xFEFC:
            ligatures.setdefault(seq[1], {})[kind] = cp
    letters = [(b, f.get("isolated", 0), f.get("final", 0), f.get("initial", 0), f.get("medial", 0))
               for b, f in sorted(forms.items()) if unicodedata.category(chr(b)) == "Lo"]
    lam_alef = [(a, f["isolated"], f["final"]) for a, f in sorted(ligatures.items())]
    return letters, lam_alef


def compositions() -> list[tuple[int, int, int]]:
    """(base, mark, composed) for every canonical pair that composes (no exclusions among these blocks)."""
    out = []
    for cp in range(0x00C0, 0x3100):
        d = unicodedata.decomposition(chr(cp)).split()
        if len(d) != 2 or d[0].startswith("<"):
            continue
        base, mark = int(d[0], 16), int(d[1], 16)
        if unicodedata.normalize("NFC", chr(base) + chr(mark)) == chr(cp):
            out.append((base, mark, cp))
    return sorted(out)


def build() -> str:
    lines = [
        "// Generated by tools/scripts/gen_unicode_tables.py from Python's unicodedata module (Unicode "
        f"{unicodedata.unidata_version}). Do not edit.",
        "",
        "// Bidirectional class of every code point that is not L, as [first, last] runs in order.",
        "constexpr BidiRange kBidiRanges[] = {",
    ]
    row = []
    for a, b, c in ranges(bidi_class):
        row.append(f"{{0x{a:04X}, 0x{b:04X}, BidiClass::{c}}}")
    lines += ["    " + ", ".join(row[i:i + 4]) + "," for i in range(0, len(row), 4)]
    lines += ["};", "", "// Nonspacing and enclosing marks (general categories Mn, Me).", "constexpr CodeRange kMarkRanges[] = {"]
    row = [f"{{0x{a:04X}, 0x{b:04X}}}" for a, b, _ in ranges(is_mark)]
    lines += ["    " + ", ".join(row[i:i + 6]) + "," for i in range(0, len(row), 6)]
    letters, lam_alef = arabic()
    lines += ["};", "",
              "// Arabic letters with their presentation forms: base, isolated, final, initial, medial (0 = none).",
              "// A letter with an initial or medial form joins on both sides, one with only a final form joins to",
              "// the letter before it.",
              "constexpr ArabicForms kArabicForms[] = {"]
    row = [f"{{0x{b:04X}, 0x{i:04X}, 0x{f:04X}, 0x{n:04X}, 0x{m:04X}}}" for b, i, f, n, m in letters]
    lines += ["    " + ", ".join(row[i:i + 3]) + "," for i in range(0, len(row), 3)]
    lines += ["};", "", "// Lam followed by this alef draws as one ligature: alef, isolated, final.",
              "constexpr LamAlef kLamAlef[] = {"]
    lines += ["    " + ", ".join(f"{{0x{a:04X}, 0x{i:04X}, 0x{f:04X}}}" for a, i, f in lam_alef) + ","]
    lines += ["};", "", "// Canonical compositions: base, mark, composed; sorted by (base, mark).",
              "constexpr Composition kCompositions[] = {"]
    row = [f"{{0x{b:04X}, 0x{m:04X}, 0x{c:04X}}}" for b, m, c in compositions()]
    lines += ["    " + ", ".join(row[i:i + 4]) + "," for i in range(0, len(row), 4)]
    lines += ["};", "", "// Characters drawn mirrored in right-to-left text: (character, its mirror), sorted.",
              "constexpr CodePair kMirrorPairs[] = {"]
    pairs = {}
    for i in range(0, len(MIRRORED), 2):
        a, b = ord(MIRRORED[i]), ord(MIRRORED[i + 1])
        pairs[a], pairs[b] = b, a
    row = [f"{{0x{a:04X}, 0x{b:04X}}}" for a, b in sorted(pairs.items())]
    lines += ["    " + ", ".join(row[i:i + 6]) + "," for i in range(0, len(row), 6)]
    lines += ["};", "", "// Paired brackets: (opening, closing), sorted by the opening one.",
              "constexpr CodePair kBracketPairs[] = {"]
    row = [f"{{0x{ord(BRACKETS[i]):04X}, 0x{ord(BRACKETS[i + 1]):04X}}}" for i in range(0, len(BRACKETS), 2)]
    row.sort()
    lines += ["    " + ", ".join(row[i:i + 6]) + "," for i in range(0, len(row), 6)]
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is not what gen_unicode_tables.py writes")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
